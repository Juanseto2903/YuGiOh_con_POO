    private void btnAtaqueDirectoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtaqueDirectoActionPerformed
        // TODO add your handling code here:
        try {
            String nomAtacante = txtNombreAtacante1.getText().trim();
            if (nomAtacante.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Ingresa el nombre del monstruo atacante.", "Campo vacío", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            int atkAtacante = Integer.parseInt(txtAtkAtacante.getText().trim());

            Monstruo atacante = new Monstruo(nomAtacante, atkAtacante, 0, "ATAQUE");

            String resultado = controlador.procesarAtaqueDirecto(atacante, jugadorDefensor);
            txtAreaHistorial.append(resultado + "\n");
            lblLpDefensor.setText("LP Jugador Defensor: " + jugadorDefensor.lp);

            if (jugadorDefensor.lp <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "¡El jugador defensor se ha quedado sin LP! ¡Derrota!", "¡Fin del Duelo!", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingresa un número entero válido en el ATK del atacante.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAtaqueDirectoActionPerformed

    private void btnAtacarMonstruoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtacarMonstruoActionPerformed
        // TODO add your handling code here:
        try {
            String nomAtacante = txtNombreAtacante1.getText().trim();
            String nomDefensor = txtNombreDefensor.getText().trim();
            if (nomAtacante.isEmpty() || nomDefensor.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Completa los nombres de ambos monstruos.", "Campos vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            int atkAtacante = Integer.parseInt(txtAtkAtacante.getText().trim());
            int atkDefensor = Integer.parseInt(txtAtkDefensor1.getText().trim());
            int defDefensor = Integer.parseInt(txtDefDefensor.getText().trim());
            String posDefensor = jComboBox2.getSelectedItem().toString();

            Monstruo atacante = new Monstruo(nomAtacante, atkAtacante, 0, "ATAQUE");
            Monstruo defensor = new Monstruo(nomDefensor, atkDefensor, defDefensor, posDefensor);

            String resultado = controlador.procesarAtaque(atacante, defensor, jugadorDefensor);
            txtAreaHistorial.append(resultado + "\n");
            lblLpDefensor.setText("LP Jugador Defensor: " + jugadorDefensor.lp);

            if (jugadorDefensor.lp <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "¡El jugador defensor se ha quedado sin LP! ¡Derrota!", "¡Fin del Duelo!", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingresa solo números enteros válidos en ATK y DEF.", "Error de Validación", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAtacarMonstruoActionPerformed

